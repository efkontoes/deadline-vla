"""Isaac Lab 3.0 backend: one rigid-body multirotor, six tiled cameras, velocity-tracking controller.

Implements the same contract as ``LightDroneEnv`` (see ``drone_env``). Obstacles are spawned once
(``MAX_OBSTACLES`` kinematic cylinders) and repositioned on every reset; unused ones are parked below
the floor, so changing scenes does not re-author the stage.

Status: written against the Isaac Lab Python API (``isaaclab.sim``, ``isaaclab.assets``,
``isaaclab.sensors.TiledCamera``) but NOT executed in this repository yet; it is the first thing to
validate at milestone M1 (go / no-go check 1). Ground-truth clearance and collision use the scene
geometry, which is exact for the cylinder worlds generated by ``scenes.build_scene``.
"""

from __future__ import annotations

import math
from typing import Any, Optional

import numpy as np

from deadlinevla.config import Config
from deadlinevla.sim.scenes import PALETTE, Scene, collides, cone_clearance

MAX_OBSTACLES = 160
MASS = 1.2  # kg, quadrotor-class airframe


def _require_isaaclab():
    try:
        from isaaclab.app import AppLauncher  # noqa: F401
    except ImportError as e:  # pragma: no cover - depends on the NVIDIA install
        raise ImportError(
            "sim.backend=isaac needs Isaac Lab 3.0 (https://isaac-sim.github.io/IsaacLab). "
            "Use sim.backend=light for the numpy backend."
        ) from e


def _yaw_quat(yaw: float) -> tuple[float, float, float, float]:
    """(w, x, y, z) rotation about +z."""
    return (math.cos(yaw / 2), 0.0, 0.0, math.sin(yaw / 2))


class IsaacDroneEnv:  # pragma: no cover - requires Isaac Sim
    _app = None

    def __init__(self, cfg: Config):
        _require_isaaclab()
        self.cfg = cfg
        if IsaacDroneEnv._app is None:
            from isaaclab.app import AppLauncher

            IsaacDroneEnv._app = AppLauncher(headless=True, enable_cameras=True).app
        self._build()
        self.scene: Optional[Scene] = None

    # ---------------------------------------------------------------------------------------------
    def _build(self) -> None:
        import isaaclab.sim as sim_utils
        import torch
        from isaaclab.assets import RigidObject, RigidObjectCfg
        from isaaclab.sensors import TiledCamera, TiledCameraCfg

        cfg = self.cfg
        self.torch = torch
        self.device = "cuda:0" if torch.cuda.is_available() else "cpu"
        self.n_sub = max(1, int(round(cfg.sim.physics_hz / cfg.drone.ctrl_hz)))
        sim_cfg = sim_utils.SimulationCfg(dt=1.0 / (cfg.drone.ctrl_hz * self.n_sub), device=self.device)
        self.sim = sim_utils.SimulationContext(sim_cfg)
        sim_utils.GroundPlaneCfg().func("/World/ground", sim_utils.GroundPlaneCfg())
        sim_utils.DomeLightCfg(intensity=2500.0).func("/World/light", sim_utils.DomeLightCfg(intensity=2500.0))

        body = sim_utils.CuboidCfg(
            size=(0.35, 0.35, 0.1),
            rigid_props=sim_utils.RigidBodyPropertiesCfg(disable_gravity=False, max_depenetration_velocity=1.0),
            mass_props=sim_utils.MassPropertiesCfg(mass=MASS),
            collision_props=sim_utils.CollisionPropertiesCfg(),
            visual_material=sim_utils.PreviewSurfaceCfg(diffuse_color=(0.1, 0.1, 0.1)),
        )
        self.drone = RigidObject(RigidObjectCfg(prim_path="/World/Drone", spawn=body,
                                                init_state=RigidObjectCfg.InitialStateCfg(pos=(0, 0, 1.5))))
        self.obstacles = []
        for i in range(MAX_OBSTACLES):
            cyl = sim_utils.CylinderCfg(
                radius=0.5, height=6.0,
                rigid_props=sim_utils.RigidBodyPropertiesCfg(kinematic_enabled=True),
                collision_props=sim_utils.CollisionPropertiesCfg(),
                visual_material=sim_utils.PreviewSurfaceCfg(diffuse_color=(0.45, 0.43, 0.40)),
            )
            self.obstacles.append(RigidObject(RigidObjectCfg(
                prim_path=f"/World/Obstacle_{i:03d}", spawn=cyl,
                init_state=RigidObjectCfg.InitialStateCfg(pos=(0, 0, -10.0)))))
        goal = sim_utils.CuboidCfg(size=(0.6, 0.6, 0.9),
                                   rigid_props=sim_utils.RigidBodyPropertiesCfg(kinematic_enabled=True),
                                   visual_material=sim_utils.PreviewSurfaceCfg(diffuse_color=(0.85, 0.15, 0.15)))
        self.goal_obj = RigidObject(RigidObjectCfg(prim_path="/World/Goal", spawn=goal,
                                                   init_state=RigidObjectCfg.InitialStateCfg(pos=(0, 0, -10.0))))

        res = cfg.tier_res[3]
        fov = math.radians(cfg.cameras.fov)
        focal = 24.0
        aperture = 2 * focal * math.tan(fov / 2)
        self.cameras = []
        for j, yaw_deg in enumerate(cfg.cameras.cam_yaws):
            spawn = (sim_utils.FisheyeCameraCfg() if cfg.cameras.model == "fisheye" else
                     sim_utils.PinholeCameraCfg(focal_length=focal, horizontal_aperture=aperture,
                                                clipping_range=(0.05, cfg.sim.max_range)))
            cam_cfg = TiledCameraCfg(
                prim_path=f"/World/Drone/cam{j}", width=res, height=res,
                data_types=["rgb", "distance_to_image_plane"], spawn=spawn,
                offset=TiledCameraCfg.OffsetCfg(pos=(0.0, 0.0, 0.05), rot=_yaw_quat(math.radians(yaw_deg)),
                                                convention="world"),
            )
            self.cameras.append(TiledCamera(cam_cfg))
        self.sim.reset()

    # ---------------------------------------------------------------------------------------------
    def reset(self, scene: Scene) -> dict[str, Any]:
        torch = self.torch
        if len(scene.obs_xy) + (scene.mover is not None) > MAX_OBSTACLES:
            raise ValueError(f"scene has more than {MAX_OBSTACLES} obstacles")
        self.scene = scene
        if scene.mover is not None:
            scene.mover.reset()
        xy, r, h = scene.circles(0.0)
        for i, obj in enumerate(self.obstacles):
            if i < len(xy):
                pose = torch.tensor([[xy[i, 0], xy[i, 1], h[i] / 2, 1.0, 0.0, 0.0, 0.0]], device=self.device)
                obj.write_root_pose_to_sim(pose)
                # radius is encoded by scaling the unit-radius-0.5 cylinder prim
                self._set_scale(obj, (r[i] / 0.5, r[i] / 0.5, h[i] / 6.0))
            else:
                obj.write_root_pose_to_sim(torch.tensor([[0, 0, -10.0, 1, 0, 0, 0]], device=self.device))
        gx, gy = scene.goal_xy
        self.goal_obj.write_root_pose_to_sim(torch.tensor([[gx, gy, 0.45, 1, 0, 0, 0]], device=self.device))
        self._set_color("/World/Goal", PALETTE[scene.goal_color])
        x, y, z, yaw = scene.start
        w, qx, qy, qz = _yaw_quat(yaw)
        self.drone.write_root_pose_to_sim(torch.tensor([[x, y, z, w, qx, qy, qz]], device=self.device))
        self.drone.write_root_velocity_to_sim(torch.zeros(1, 6, device=self.device))
        self.t = 0.0
        self.distance = 0.0
        self._last_xy = np.array([x, y])
        self.sim.step(render=True)
        self._update_sensors()
        return self._obs(self._info(False, False, False))

    def step(self, v_cmd: np.ndarray) -> tuple[dict[str, Any], dict[str, Any]]:
        torch = self.torch
        d = self.cfg.drone
        v_cmd = np.asarray(v_cmd, dtype=np.float64)
        collision = goal = oob = False
        dt = self.sim.get_physics_dt()
        if self.scene.mover is not None:
            pos0, vel0, _ = self._pose()
            self.scene.mover.steer(self.t, pos0, vel0)
        for k in range(self.n_sub):
            pos, vel, yaw = self._pose()
            cy, sy = math.cos(yaw), math.sin(yaw)
            target = np.array([cy * v_cmd[0] - sy * v_cmd[1], sy * v_cmd[0] + cy * v_cmd[1], v_cmd[2]])
            acc = (target - vel) / d.tau_vel
            na = float(np.linalg.norm(acc))
            if na > d.a_max:
                acc *= d.a_max / na
            force = MASS * (acc + np.array([0.0, 0.0, 9.81]))
            f = torch.tensor(force, dtype=torch.float32, device=self.device).view(1, 1, 3)
            self.drone.set_external_force_and_torque(f, torch.zeros_like(f), is_global=True)
            self.drone.write_data_to_sim()
            # yaw rate is tracked directly by the attitude loop
            rv = self.drone.data.root_vel_w.clone()
            rv[0, 3:5] = 0.0
            rv[0, 5] = float(np.clip(v_cmd[3], -d.yaw_rate_max, d.yaw_rate_max))
            self.drone.write_root_velocity_to_sim(rv)
            if self.scene.mover is not None:
                self._move_mover()
            self.sim.step(render=(k == self.n_sub - 1))
            self.drone.update(dt)
            self.t += dt
            pos, _, _ = self._pose()
            self.distance += float(np.linalg.norm(pos[:2] - self._last_xy))
            self._last_xy = pos[:2].copy()
            if collides(self.scene, pos, self.t, d.radius):
                collision = True
                break
            if np.linalg.norm(pos[:2] - self.scene.goal_xy) < self.cfg.sim.goal_radius:
                goal = True
                break
        pos, _, _ = self._pose()
        oob = bool((np.abs(pos[:2]) > self.scene.arena / 2 + 2.0).any())
        self._update_sensors()
        info = self._info(collision, goal, oob)
        return self._obs(info), info

    def clearance(self, v_hat: Optional[np.ndarray], cone_deg: float) -> float:
        pos, _, _ = self._pose()
        return cone_clearance(self.scene, pos, self.t, v_hat, cone_deg, self.cfg.drone.radius,
                              self.cfg.sim.max_range)

    # ---------------------------------------------------------------------------------------------
    def _pose(self) -> tuple[np.ndarray, np.ndarray, float]:
        data = self.drone.data
        pos = data.root_pos_w[0].cpu().numpy().astype(np.float64)
        vel = data.root_lin_vel_w[0].cpu().numpy().astype(np.float64)
        w, x, y, z = data.root_quat_w[0].cpu().numpy()
        yaw = math.atan2(2 * (w * z + x * y), 1 - 2 * (y * y + z * z))
        return pos, vel, yaw

    def _move_mover(self) -> None:
        m = self.scene.mover
        p = m.pos(self.t)
        idx = len(self.scene.obs_xy)
        pose = self.torch.tensor([[p[0], p[1], m.h / 2, 1.0, 0, 0, 0]], device=self.device)
        self.obstacles[idx].write_root_pose_to_sim(pose)

    def _set_scale(self, obj, scale) -> None:
        from pxr import Gf, UsdGeom

        prim = obj.root_physx_view.prim_paths[0] if hasattr(obj, "root_physx_view") else obj.cfg.prim_path
        stage = self.sim.stage
        xf = UsdGeom.Xformable(stage.GetPrimAtPath(prim))
        ops = [op for op in xf.GetOrderedXformOps() if op.GetOpType() == UsdGeom.XformOp.TypeScale]
        (ops[0] if ops else xf.AddScaleOp()).Set(Gf.Vec3f(*scale))

    def _set_color(self, prim_path: str, rgb) -> None:
        import isaaclab.sim as sim_utils

        mat = sim_utils.PreviewSurfaceCfg(diffuse_color=tuple(c / 255 for c in rgb))
        mat.func(f"{prim_path}/material", mat)
        sim_utils.bind_visual_material(prim_path, f"{prim_path}/material")

    def _update_sensors(self) -> None:
        dt = self.sim.get_physics_dt() * self.n_sub
        for cam in self.cameras:
            cam.update(dt)

    def _info(self, collision: bool, goal: bool, oob: bool) -> dict[str, Any]:
        _, vel, _ = self._pose()
        speed = float(np.linalg.norm(vel))
        v_hat = vel / speed if speed >= self.cfg.budget.hover_speed else None
        timeout = self.t >= self.cfg.sim.max_episode_s - 1e-9
        done = collision or goal or oob or timeout
        return {"collision": collision, "goal_reached": goal, "out_of_bounds": oob, "timeout": timeout,
                "done": done, "clearance": self.clearance(v_hat, self.cfg.budget.cone_deg), "time": self.t,
                "distance": self.distance}

    def _obs(self, info: dict[str, Any]) -> dict[str, Any]:
        pos, vel, yaw = self._pose()
        rgb = np.stack([c.data.output["rgb"][0, ..., :3].cpu().numpy() for c in self.cameras]).astype(np.uint8)
        depth = np.stack([c.data.output["distance_to_image_plane"][0, ..., 0].cpu().numpy()
                          for c in self.cameras]).astype(np.float32)
        depth = np.nan_to_num(depth, nan=self.cfg.sim.max_range, posinf=self.cfg.sim.max_range)
        cy, sy = math.cos(yaw), math.sin(yaw)
        vb = np.array([cy * vel[0] + sy * vel[1], -sy * vel[0] + cy * vel[1], vel[2]])
        ang = self.drone.data.root_ang_vel_w[0].cpu().numpy()
        w, x, y, z = self.drone.data.root_quat_w[0].cpu().numpy()
        roll = math.atan2(2 * (w * x + y * z), 1 - 2 * (x * x + y * y))
        pitch = math.asin(max(-1.0, min(1.0, 2 * (w * y - z * x))))
        state = np.array([vb[0], vb[1], vb[2], ang[2], roll, pitch, pos[2]])
        return {"images": rgb, "depth": depth, "state": state, "vel_body": vb,
                "instruction": self.scene.instruction, "info": info,
                "privileged": {"scene": self.scene, "pos": pos, "vel": vel, "yaw": yaw, "time": self.t}}
